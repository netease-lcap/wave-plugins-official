/**
 * 检查 NASL 关键词冲突
 *
 * @description 检查给定的单词列表中是否包含 NASL 系统的保留关键词
 * 支持按类型检查（common、entityName、enumName 等）
 *
 * @param {Array<string>} types - 要检查的关键词类型列表
 *
 * @returns {Function} 返回一个函数，接收单词列表参数
 *
 * @example
 * const checker = checkNASLKeywords(['common', 'entityName']);
 * const conflicts = checker(['User', 'class', 'MyEntity']);
 * // 返回 ['class'] （class 是 NASL 保留关键词）
 */
export const checkNASLKeywords =
  (types = []) =>
  (words = []) => {
    const set = new Set();

    types.forEach((type) => {
      const keywords = KEYWORDS_MAP[type];

      const filter = (word) => {
        word = word.toLowerCase();
        return keywords.has(word);
      };

      const forEach = (word) => set.add(word);

      words.filter(filter).forEach(forEach);
    });

    return Array.from(set);
  };
